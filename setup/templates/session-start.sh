#!/usr/bin/env bash
# session-start.sh — runs at SessionStart. Three jobs:
#   1. Flatten CLAUDE.md + .claude/context/*.md + lessons.md + last 3 session-log entries
#      into .claude/agent-context.md so subagents get all project context via
#      a single Read instead of re-reading multiple files per invocation.
#      Falls back to .claude/context.md if .claude/context/ folder not present (legacy).
#   2. .pending-lesson-candidates marker exists newer than lessons.md →
#      prompt Claude to invoke @lesson-curator before doing other work.
#   3. lessons.md is stale (>30 days) → prompt Claude to verify the
#      project's recorded conventions still match reality.
# If any reminder fires, output a JSON object with `additionalContext`.
# Always exits 0 — never blocks session start.

CLAUDE_DIR="$(cd "$(dirname "$0")/.." && pwd)"
PROJECT_ROOT="$(cd "$CLAUDE_DIR/.." && pwd)"
MARKER="$CLAUDE_DIR/.pending-lesson-candidates"
LESSONS="$CLAUDE_DIR/lessons.md"
CONTEXT_DIR="$CLAUDE_DIR/context"
CONTEXT_LEGACY="$CLAUDE_DIR/context.md"
SESSION_LOG="$CLAUDE_DIR/session-log.md"
CLAUDE_MD="$PROJECT_ROOT/CLAUDE.md"
AGENT_CTX="$CLAUDE_DIR/agent-context.md"

# Job 1: Flatten project context into agent-context.md.
# Subagents Read this single file at startup instead of multiple files.
# Regenerated every session start so it reflects current state of all sources.
{
    echo "<!-- AUTO-GENERATED by .claude/scripts/session-start.sh — do NOT edit by hand."
    echo "     Source files: CLAUDE.md + .claude/context/*.md (or .claude/context.md legacy) + .claude/lessons.md + .claude/session-log.md (last 3 entries)."
    echo "     Regenerated at every SessionStart. To refresh mid-session, re-run this script. -->"
    echo ""
    if [[ -f "$CLAUDE_MD" ]]; then
        echo "# === CLAUDE.md (project facts + architecture + permanent rules) ==="
        echo ""
        cat "$CLAUDE_MD"
        echo ""
    fi
    # 3-file context model (preferred)
    if [[ -d "$CONTEXT_DIR" ]]; then
        for ctx_file in "$CONTEXT_DIR/architecture.md" "$CONTEXT_DIR/tech-stack.md" "$CONTEXT_DIR/coding-standards.md"; do
            if [[ -f "$ctx_file" ]]; then
                ctx_name=$(basename "$ctx_file")
                echo "# === .claude/context/$ctx_name ==="
                echo ""
                cat "$ctx_file"
                echo ""
            fi
        done
    elif [[ -f "$CONTEXT_LEGACY" ]]; then
        # Legacy: single .claude/context.md (pre-fusion installs)
        echo "# === .claude/context.md (current phase + domain + stakeholders + constraints) ==="
        echo ""
        cat "$CONTEXT_LEGACY"
        echo ""
    fi
    if [[ -f "$LESSONS" ]]; then
        echo "# === .claude/lessons.md (project-specific overrides) ==="
        echo ""
        cat "$LESSONS"
        echo ""
    fi
    if [[ -f "$SESSION_LOG" ]]; then
        echo "# === .claude/session-log.md (last 3 entries) ==="
        echo ""
        # Take only first 3 H2 sections (most recent entries; file is reverse-chronological)
        awk '
            BEGIN { keep = 3; count = 0 }
            /^## / { count++; if (count > keep) exit }
            { print }
        ' "$SESSION_LOG"
        echo ""
    fi
} > "$AGENT_CTX" 2>/dev/null

MSG=""

# Check 1: pending lesson candidates from prior sessions
if [[ -f "$MARKER" ]]; then
    NEWER=true
    if [[ -f "$LESSONS" ]] && [[ "$LESSONS" -nt "$MARKER" ]]; then
        NEWER=false
    fi
    if [[ "$NEWER" == "true" ]]; then
        COUNT=$(wc -l < "$MARKER" 2>/dev/null | tr -d ' ')
        REVIEWERS=$(awk '{print $2}' "$MARKER" 2>/dev/null | sort -u | paste -sd, - | sed 's/,/, /g')
        MSG="REMINDER: $COUNT un-curated Lesson Candidate marker(s) from prior sessions (from: ${REVIEWERS:-unknown}). Tell the user to reply with one of: (1) 'curate' — invoke @lesson-curator and walk through diff approval before applying any lesson; (2) 'discard' — clear the marker without applying anything (treats prior candidates as no longer relevant); (3) 'skip' — defer; the reminder will fire again next session. Don't silently proceed past this — un-curated candidates go stale and lessons.md drifts from reality. Markers older than 60 days are auto-discarded by the Stop hook to prevent unbounded accumulation."
    fi
fi

# Check 2: lessons.md staleness (>30 days)
# Lessons change rarely; this catches projects whose stack/conventions have
# drifted from what was recorded — not a daily nag.
if [[ -f "$LESSONS" ]] && find "$LESSONS" -mtime +30 2>/dev/null | grep -q .; then
    LESSONS_AGE_DAYS=$(( ( $(date +%s) - $(date -r "$LESSONS" +%s) ) / 86400 ))
    LESSONS_MSG="REMINDER: .claude/lessons.md has not been updated in $LESSONS_AGE_DAYS days. Recorded project conventions (test framework, DI container, ORM, auth scheme, frozen names, stack deltas) may no longer match reality. Before any agent treats lessons.md as authoritative, ask me whether anything has changed since the last update. If changes have occurred, propose a refresh and run @lesson-curator. If nothing has changed, touch the file (re-save as-is) so the reminder clears."
    if [[ -n "$MSG" ]]; then
        MSG="$MSG\\n\\n$LESSONS_MSG"
    else
        MSG="$LESSONS_MSG"
    fi
fi

# Check 3: session-log.md "previous session not logged" detection.
# If the file exists but its most recent H2 (## YYYY-MM-DD) is older than 24h
# AND the project has commits in the last 24h (signal that work happened),
# the previous session probably ended without writing an entry. Remind to log.
if [[ -f "$SESSION_LOG" ]]; then
    # Grab the most recent date heading (lines that match ^## YYYY-MM-DD)
    LATEST_LOG_DATE=$(grep -m 1 '^## [0-9]\{4\}-[0-9]\{2\}-[0-9]\{2\}' "$SESSION_LOG" 2>/dev/null | sed 's/^## //' | awk '{print $1}')
    TODAY=$(date -u +%F)
    if [[ -n "$LATEST_LOG_DATE" && "$LATEST_LOG_DATE" != "$TODAY" && "$LATEST_LOG_DATE" != "YYYY-MM-DD" ]]; then
        # Check for recent commits as a "work happened" signal (project root = parent of .claude)
        RECENT_COMMITS=$(cd "$PROJECT_ROOT" && git log --since="24 hours ago" --oneline 2>/dev/null | wc -l | tr -d ' ' || echo 0)
        if [[ "$RECENT_COMMITS" -gt 0 ]]; then
            LOG_MSG="REMINDER: .claude/session-log.md last entry is dated $LATEST_LOG_DATE but git shows $RECENT_COMMITS commit(s) in the last 24 hours. The previous session probably ended without writing a log entry. At the end of THIS session — or now if you remember what was done — add a '## $TODAY — short title' entry summarising: what was worked on, decisions made, open threads. The Stop hook will trim to last 10 entries automatically."
            if [[ -n "$MSG" ]]; then
                MSG="$MSG\\n\\n$LOG_MSG"
            else
                MSG="$LOG_MSG"
            fi
        fi
    fi
fi

[[ -n "$MSG" ]] || exit 0

cat <<JSON
{
  "hookSpecificOutput": {
    "hookEventName": "SessionStart",
    "additionalContext": "$MSG"
  }
}
JSON

exit 0
