# session-start.ps1 - runs at SessionStart. Three jobs:
#   1. Flatten CLAUDE.md + .claude/context/*.md + lessons.md + last 3 session-log entries
#      into .claude/agent-context.md so subagents get all project context via
#      a single Read instead of re-reading multiple files per invocation.
#      Falls back to .claude/context.md if .claude/context/ folder not present (legacy).
#   2. .pending-lesson-candidates marker exists newer than lessons.md ->
#      prompt Claude to invoke @lesson-curator before doing other work.
#   3. lessons.md is stale (>30 days) -> prompt Claude to verify the
#      project's recorded conventions still match reality.
# If any reminder fires, output a JSON object with additionalContext.
# Always exits 0 - never blocks session start.

$ErrorActionPreference = 'SilentlyContinue'
$claudeDir   = Split-Path $PSScriptRoot -Parent
$projectRoot = Split-Path $claudeDir -Parent
$marker      = Join-Path $claudeDir '.pending-lesson-candidates'
$lessons     = Join-Path $claudeDir 'lessons.md'
$contextDir  = Join-Path $claudeDir 'context'
$contextLegacy = Join-Path $claudeDir 'context.md'
$sessionLog  = Join-Path $claudeDir 'session-log.md'
$claudeMd    = Join-Path $projectRoot 'CLAUDE.md'
$agentCtx    = Join-Path $claudeDir 'agent-context.md'
$minimalCtx  = Join-Path $claudeDir 'context-minimal.md'

# Job 1: Flatten project context into agent-context.md.
# Subagents Read this single file at startup instead of multiple files.
# Regenerated every session start so it reflects current state.
$lines = New-Object System.Collections.Generic.List[string]
$lines.Add('<!-- AUTO-GENERATED by .claude/scripts/session-start.ps1 - do NOT edit by hand.')
$lines.Add('     Source files: CLAUDE.md + .claude/context/*.md (or .claude/context.md legacy) + .claude/lessons.md + .claude/session-log.md (last 3 entries).')
$lines.Add('     Regenerated at every SessionStart. To refresh mid-session, re-run this script. -->')
$lines.Add('')
if (Test-Path $claudeMd) {
    $lines.Add('# === CLAUDE.md (project facts + architecture + permanent rules) ===')
    $lines.Add('')
    Get-Content $claudeMd | ForEach-Object { $lines.Add($_) }
    $lines.Add('')
}
# 3-file context model (preferred)
if (Test-Path $contextDir -PathType Container) {
    foreach ($ctxFile in @('architecture.md', 'tech-stack.md', 'coding-standards.md')) {
        $ctxPath = Join-Path $contextDir $ctxFile
        if (Test-Path $ctxPath) {
            $lines.Add("# === .claude/context/$ctxFile ===")
            $lines.Add('')
            Get-Content $ctxPath | ForEach-Object { $lines.Add($_) }
            $lines.Add('')
        }
    }
} elseif (Test-Path $contextLegacy) {
    # Legacy: single .claude/context.md (pre-fusion installs)
    $lines.Add('# === .claude/context.md (current phase + domain + stakeholders + constraints) ===')
    $lines.Add('')
    Get-Content $contextLegacy | ForEach-Object { $lines.Add($_) }
    $lines.Add('')
}
if (Test-Path $lessons) {
    $lines.Add('# === .claude/lessons.md (project-specific overrides) ===')
    $lines.Add('')
    Get-Content $lessons | ForEach-Object { $lines.Add($_) }
    $lines.Add('')
}
if (Test-Path $sessionLog) {
    $lines.Add('# === .claude/session-log.md (last 3 entries) ===')
    $lines.Add('')
    $keep = 3
    $count = 0
    foreach ($line in Get-Content $sessionLog) {
        if ($line -match '^## ') {
            $count++
            if ($count -gt $keep) { break }
        }
        $lines.Add($line)
    }
    $lines.Add('')
}
Set-Content -Path $agentCtx -Value $lines -Encoding UTF8

# Job 2: Generate context-minimal.md — ~30-token @-import for the main session.
# Contains only recent lessons (top 5) and last session header.
# Service name, project facts, and key files are already in CLAUDE.md which the main session
# loads via the @-import chain — duplicating them here adds tokens with no new information.
$minLines = New-Object System.Collections.Generic.List[string]
$minLines.Add('<!-- AUTO-GENERATED by session-start.ps1 - minimal session context (@-imported by CLAUDE.md).')
$minLines.Add('     Do NOT edit by hand. Regenerated at every SessionStart. -->')
$minLines.Add('')
# Top 5 lesson bullets (newest first - curator inserts at top of each section)
if (Test-Path $lessons) {
    $minLines.Add('## Recent Lessons (top 5)')
    $bulletCount = 0
    foreach ($line in Get-Content $lessons) {
        if ($line -match '^- ' -and $bulletCount -lt 5) { $minLines.Add($line); $bulletCount++ }
    }
    $minLines.Add('')
}
# Last session-log entry header only (date + title, no body)
if (Test-Path $sessionLog) {
    $minLines.Add('## Last Session')
    $lastHeader = Get-Content $sessionLog | Where-Object { $_ -match '^## ' } | Select-Object -First 1
    $minLines.Add($(if ($lastHeader) { $lastHeader } else { '_none yet_' }))
    $minLines.Add('')
}
Set-Content -Path $minimalCtx -Value $minLines -Encoding UTF8

# Staleness guard: if context-minimal.md is older than 24h, the hook likely failed
# silently last session. The stale file would then be auto-imported with outdated lessons.
$stalenessWarning = $null
if (Test-Path $minimalCtx) {
    $minimalAge = (New-TimeSpan -Start (Get-Item $minimalCtx).LastWriteTime -End (Get-Date)).TotalSeconds
    if ($minimalAge -gt 86400) {
        $stalenessWarning = "WARNING: .claude/context-minimal.md is more than 24h old ($([int]$minimalAge)s). The SessionStart hook may have failed silently last session — lessons shown in this file may be stale. Re-run 'pwsh -File .claude/scripts/session-start.ps1' to refresh, or restart Claude Code."
    }
}

$messages = @()
if ($stalenessWarning) { $messages += $stalenessWarning }

# Check 1: pending lesson candidates from prior sessions
if (Test-Path $marker) {
    $markerNewer = $true
    if (Test-Path $lessons) {
        $markerTime  = (Get-Item $marker).LastWriteTime
        $lessonsTime = (Get-Item $lessons).LastWriteTime
        if ($lessonsTime -gt $markerTime) { $markerNewer = $false }
    }
    if ($markerNewer) {
        $lines = Get-Content -Path $marker -ErrorAction SilentlyContinue
        $count = ($lines | Measure-Object -Line).Lines
        $reviewerList = ($lines | ForEach-Object { ($_ -split '\s+')[1] }) | Sort-Object -Unique | Where-Object { $_ }
        $reviewers = if ($reviewerList) { $reviewerList -join ', ' } else { 'unknown' }
        $messages += "REMINDER: $count un-curated Lesson Candidate marker(s) from prior sessions (from: $reviewers). Tell the user to reply with one of: (1) 'curate' - invoke @lesson-curator and walk through diff approval before applying any lesson; (2) 'discard' - clear the marker without applying anything (treats prior candidates as no longer relevant); (3) 'skip' - defer; the reminder will fire again next session. Don't silently proceed past this - un-curated candidates go stale and lessons.md drifts from reality. Markers older than 60 days are auto-discarded by the Stop hook to prevent unbounded accumulation."
    }
}

# Check 2: lessons.md staleness (>30 days)
# Lessons change rarely; this catches projects whose stack/conventions have
# drifted from what was recorded - not a daily nag.
if (Test-Path $lessons) {
    $lessonsAgeDays = (New-TimeSpan -Start (Get-Item $lessons).LastWriteTime -End (Get-Date)).Days
    if ($lessonsAgeDays -gt 30) {
        $messages += "REMINDER: .claude/lessons.md has not been updated in $lessonsAgeDays days. Recorded project conventions (test framework, DI container, ORM, auth scheme, frozen names, stack deltas) may no longer match reality. Before any agent treats lessons.md as authoritative, ask me whether anything has changed since the last update. If changes have occurred, propose a refresh and run @lesson-curator. If nothing has changed, touch the file (re-save as-is) so the reminder clears."
    }
}

# Check 3: session-log.md "previous session not logged" detection.
# If the most recent ## YYYY-MM-DD heading is older than today AND the project
# has commits in the last 24h, the previous session probably ended without
# writing an entry. Remind to log.
if (Test-Path $sessionLog) {
    $latestLogDate = $null
    foreach ($line in Get-Content $sessionLog) {
        if ($line -match '^## (\d{4}-\d{2}-\d{2})') {
            $latestLogDate = $matches[1]
            break
        }
    }
    $today = (Get-Date).ToUniversalTime().ToString('yyyy-MM-dd')
    if ($latestLogDate -and $latestLogDate -ne $today -and $latestLogDate -ne 'YYYY-MM-DD') {
        # Check git for recent commits as "work happened" signal
        Push-Location $projectRoot
        try {
            $recentCommits = (& git log --since="24 hours ago" --oneline 2>$null | Measure-Object -Line).Lines
        } catch {
            $recentCommits = 0
        } finally {
            Pop-Location
        }
        if ($recentCommits -gt 0) {
            $messages += "REMINDER: .claude/session-log.md last entry is dated $latestLogDate but git shows $recentCommits commit(s) in the last 24 hours. The previous session probably ended without writing a log entry. At the end of THIS session - or now if you remember what was done - add a '## $today - short title' entry summarising: what was worked on, decisions made, open threads. The Stop hook will trim to last 3 entries automatically."
        }
    }
}

if ($messages.Count -eq 0) { exit 0 }

$payload = @{
    hookSpecificOutput = @{
        hookEventName     = 'SessionStart'
        additionalContext = ($messages -join "`n`n")
    }
}
$payload | ConvertTo-Json -Depth 5 -Compress

exit 0
